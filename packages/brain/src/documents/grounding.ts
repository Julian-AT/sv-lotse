import type { BoundingBox } from "@lotse/protocol";
import {
  DocumentError,
  type DocumentPage,
  type DocumentStatement,
  extractionSchema,
  statementSchema,
} from "./schema.ts";

/** Reconcile only whitespace; returned text is always the unchanged source substring. */
export function sourceQuote(text: string, quote: string): string {
  if (text.includes(quote)) return quote;
  const positions: number[] = [];
  let compact = "";
  for (let index = 0; index < text.length; index++) {
    const character = text[index];
    if (character !== undefined && !/\s/u.test(character)) {
      compact += character;
      positions.push(index);
    }
  }
  const target = quote.replace(/\s/gu, "");
  const offset = compact.indexOf(target);
  const start = positions[offset];
  const end = positions[offset + target.length - 1];
  if (!target || offset < 0 || start === undefined || end === undefined)
    throw new DocumentError("ungrounded_statement");
  return text.slice(start, end + 1);
}

/** Positions are always derived from source lines, never generated by a model. */
export function locateQuote(
  page: DocumentPage,
  quote: string,
  start = page.text.indexOf(quote),
): BoundingBox {
  if (!quote.trim() || start < 0 || page.text.slice(start, start + quote.length) !== quote)
    throw new DocumentError("ungrounded_statement");
  let offset = 0;
  const boxes = page.lines.flatMap((line) => {
    const end = offset + line.text.length;
    const included = end > start && offset < start + quote.length;
    offset = end + 1;
    return included ? [line.bbox] : [];
  });
  if (!boxes.length) throw new DocumentError("ungrounded_statement");
  const x = Math.min(...boxes.map((box) => box.x));
  const y = Math.min(...boxes.map((box) => box.y));
  return {
    x,
    y,
    width: Math.max(...boxes.map((box) => box.x + box.width)) - x,
    height: Math.max(...boxes.map((box) => box.y + box.height)) - y,
  };
}
export function groundStatements(
  raw: unknown,
  pages: readonly DocumentPage[],
): DocumentStatement[] {
  const candidates = extractionSchema.parse(raw).statements;
  const statements = candidates.map((candidate) => {
    const page = pages.find((entry) => entry.page === candidate.page);
    if (!page) throw new DocumentError("ungrounded_statement");
    const quote = sourceQuote(page.text, candidate.quote);
    return statementSchema.parse({ ...candidate, quote, bbox: locateQuote(page, quote) });
  });
  return statements.filter(
    (statement, index) =>
      statements.findIndex(
        (other) =>
          other.type === statement.type &&
          other.page === statement.page &&
          other.quote === statement.quote,
      ) === index,
  );
}
