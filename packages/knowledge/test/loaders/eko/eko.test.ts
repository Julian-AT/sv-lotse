test("AC1 parses all 6,985 real packs and ten named packs match independently transcribed raw values", async () => {
  const eko = await loadEko(dir);
  const raw = new TextDecoder("windows-1252").decode(await readFile(join(dir, "medikament.txt")));
  expect(eko.packs).toHaveLength(raw.trimEnd().split(/\r?\n/u).length);
  expect(eko.packs).toHaveLength(6985);
  // Transcribed from the original fixed-width export, not generated by the parser.
  const samples = [
    ["0001063", "Agaffin Abführgel", "green", "100", "ml", 385, ""],
    ["0001318", "Akineton 2 mg Tabl.", "green", "50", "St", 605, ""],
    ["0001324", "Akineton 2 mg Tabl.", "green", "100", "St", 960, ""],
    ["1276230", "Pentasa 1 g Zäpf.", "yellow-re2", "28", "St", 4760, "RE2"],
    ["2421504", "Octanate 50 IE/ml", "yellow-re1", "1", "St", 19515, "RE1"],
    ["3542285", "Toctino 30 mg Weichkaps.", "yellow-re1", "30", "St", 36095, "RE1"],
    ["3919778", "Bosulif 100 mg Filmtabl.", "green", "28", "St", 18125, "IND"],
    ["4207761", "Bosulif 100 mg Filmtabl.", "green", "112", "St", 65585, "IND"],
    ["4471222", "Mavenclad 10 mg Filmtabl.", "yellow-re1", "1", "St", 174585, "RE1"],
    ["1281550", "Euthyrox 50 mcg Tabl.", "green", "20", "St", 90, ""],
  ] as const;
  for (const [pharmaNumber, name, box, quantity, unit, priceCents, codes] of samples) {
    expect(eko.packs.find((pack) => pack.pharmaNumber === pharmaNumber)).toMatchObject({
      pharmaNumber,
      name,
      box,
      quantity,
      unit,
      priceCents,
      codes,
    });
  }
  expect(new Set(eko.packs.map((pack) => pack.pharmaNumber)).size).toBe(6985);
});

test("AC2 FR-M1 exact lookup returns separate coverage-only packs and verbatim rules", async () => {
  const eko = await loadEko(dir);
  const ruleRows = new TextDecoder("windows-1252")
    .decode(await readFile(join(dir, "regeltext.txt")))
    .trimEnd()
    .split(/\r?\n/u);
  const rules = new Map(ruleRows.map((row) => [row.slice(1, 8), row.slice(11, -1)]));
  for (const [name, box, approvalRequired] of [
    ["Akineton 2 mg Tabl.", "green", false],
    ["Mavenclad 10 mg Filmtabl.", "yellow-re1", true],
    ["Pentasa 1 g Zäpf.", "yellow-re2", false],
    ["Bosulif 100 mg Filmtabl.", "green", false],
  ] as const) {
    const result = eko.lookupCoverage({ medicineNameExact: name });
    const expected = eko.packs.filter((pack) => pack.name === name);
    expect(result.listed).toBe(true);
    expect(result.packs).toHaveLength(expected.length);
    for (const pack of result.packs) {
      expect(pack).toMatchObject({
        box,
        approvalRequired,
        ruleText: rules.get(pack.pharmaNumber) ?? null,
        textModified: false,
      });
      expect(Object.keys(pack).sort()).toEqual(
        [
          "approvalRequestedBy",
          "approvalRequired",
          "approvalRule",
          "box",
          "conditionsFlag",
          "pharmaNumber",
          "quantity",
          "ruleText",
          "textModified",
          "unit",
        ].sort(),
      );
    }
  }
  expect(eko.lookupCoverage({ medicineNameExact: "Mavenclad 10 mg Filmtabl." }).packs).toHaveLength(
    3,
  );
  // Every product is projected explicitly: no ATC, indication text, price or other product names.
  for (const name of new Set(eko.packs.map((pack) => pack.name))) {
    const result = eko.lookupCoverage({ medicineNameExact: name });
    expect(Object.keys(result).sort()).toEqual(
      ["listed", "packs", "prescriptionFee", "capRule", "exemptionRule", "sources"].sort(),
    );
    for (const pack of result.packs) {
      const original = rules.get(pack.pharmaNumber) ?? null;
      const expected =
        original?.replace(
          /\b[A-Z]\d{2}(?:[A-Z](?:[A-Z](?:\d{2})?)?)?\b/gu,
          "[ATC-Code entfernt]",
        ) ?? null;
      expect(pack.ruleText).toBe(expected);
      expect(pack.textModified).toBe(expected !== original);
      expect(pack.ruleText ?? "").not.toMatch(/\b[A-Z]\d{2}(?:[A-Z](?:[A-Z](?:\d{2})?)?)?\b/u);
      expect(Object.keys(pack).sort()).toEqual(
        [
          "approvalRequestedBy",
          "approvalRequired",
          "approvalRule",
          "box",
          "conditionsFlag",
          "pharmaNumber",
          "quantity",
          "ruleText",
          "textModified",
          "unit",
        ].sort(),
      );
    }
  }
  const unknown = eko.lookupCoverage({ medicineNameExact: "Akineton" });
  expect(unknown).toMatchObject({ listed: false, packs: [] });
  expect(unknown.prescriptionFee).toMatchObject({ amountCents: 755, currency: "EUR", year: 2026 });
  expect(unknown.capRule).toMatchObject({ incomePercent: 2, year: 2026 });
  expect(unknown.exemptionRule).toContain("Antrag");
  expect(() => eko.lookupCoverage({ medicineNameExact: "  " })).toThrow();
});

test("AC3 FR-M1 decodes umlauts and matches only complete names ignoring case, whitespace and Unicode composition", async () => {
  const eko = await loadEko(dir);
  expect(eko.packs.find((pack) => pack.pharmaNumber === "0001063")?.name).toBe("Agaffin Abführgel");
  expect(
    eko.lookupCoverage({ medicineNameExact: "  AGAFFIN\tABFÜHRGEL \n".normalize("NFD") }),
  ).toEqual(eko.lookupCoverage({ medicineNameExact: "Agaffin Abführgel" }));
  expect(eko.lookupCoverage({ medicineNameExact: "Agaffin Abfuhrgel" }).listed).toBe(false);
  expect(eko.lookupCoverage({ medicineNameExact: "Agaffin Abführgel extra" }).listed).toBe(false);
});

const fixtures: string[] = [];
afterEach(async () => {
  vi.unstubAllEnvs();
  await Promise.all(fixtures.splice(0).map((root) => rm(root, { recursive: true, force: true })));
});
async function fixture(): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), "eko-test-"));
  fixtures.push(root);
  await cp(dir, root, { recursive: true });
  return root;
}

test("FR-M1 supports UTF-8 v2 texts with HTML entities when legacy texts are absent", async () => {
  const root = await fixture();
  await rm(join(root, "regeltext.txt"));
  await rm(join(root, "indtext.txt"));
  const eko = await loadEko(root);
  const pack = eko.lookupCoverage({ medicineNameExact: "Pentasa 1 g Zäpf." }).packs[0];
  const original = await readFile(join(root, "regeltext_v2.txt"), "utf8");
  const row = original.split(/\r?\n/u).find((line) => line.startsWith("|1276230|"));
  expect(row).toBeDefined();
  expect(pack?.ruleText).toBeTruthy();
  expect(pack?.ruleText).not.toMatch(/&(?:uuml|ouml|auml);|<br/u);
});

test.each([
  ["medikament.txt", "short row\r\n", "195 characters"],
  ["regeltext.txt", "|9999999|;|orphan rule|\r\n", "unknown pharma number"],
  ["indtext.txt", "malformed\r\n", "invalid text record"],
  ["atccode.txt", "bad\r\n", "ATC"],
])(
  "FR-M1 rejects malformed or unlinked %s instead of silently dropping data",
  async (file, content, message) => {
    const root = await fixture();
    await writeFile(join(root, file), content);
    await expect(loadEko(root).then(() => undefined)).rejects.toThrow(message);
  },
);

test("FR-M1 rejects duplicate packs and missing mandatory yellow rule texts", async () => {
  const root = await fixture();
  const original = await readFile(join(root, "medikament.txt"));
  const end = original.indexOf(10) + 1;
  await writeFile(
    join(root, "medikament.txt"),
    Buffer.concat([original, original.subarray(0, end)]),
  );
  await expect(loadEko(root).then(() => undefined)).rejects.toThrow("duplicate pharma number");
  await writeFile(join(root, "medikament.txt"), original);
  await writeFile(join(root, "regeltext.txt"), "");
  await expect(loadEko(root).then(() => undefined)).rejects.toThrow("missing rule text");
});

test("AC2 never exposes ATC codes embedded in verbatim coverage rules", async () => {
  const eko = await loadEko(dir);
  // The real export contains D11AX18 in this rule; only that code may change.
  const result = eko.lookupCoverage({ medicineNameExact: "Aldara 5 % Creme" });
  expect(result.listed).toBe(true);
  const raw = new TextDecoder("windows-1252").decode(await readFile(join(dir, "regeltext.txt")));
  const row = raw.split(/\r?\n/u).find((line) => line.startsWith("|1341602|"));
  expect(row).toContain("D11AX18");
  const pack = result.packs.find((entry) => entry.pharmaNumber === "1341602");
  expect(pack).toBeDefined();
  expect(pack?.textModified).toBe(true);
  expect(pack?.ruleText).toBe(row?.slice(11, -1).replaceAll("D11AX18", "[ATC-Code entfernt]"));
  expect(
    result.packs.some((pack) =>
      /\b[A-Z]\d{2}(?:[A-Z](?:[A-Z](?:\d{2})?)?)?\b/u.test(pack.ruleText ?? ""),
    ),
  ).toBe(false);
});
