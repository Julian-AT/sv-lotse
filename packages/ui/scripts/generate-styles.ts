import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { colorTokens, materialTokens, tokens } from "../src/tokens/index";

function declarations(values: Readonly<Record<string, string>>): string {
  return Object.entries(values)
    .map(([name, value]) => `  --lotse-${name}: ${value};`)
    .join("\n");
}
const source = await readFile(new URL("../src/styles/components.css", import.meta.url), "utf8");
const css = `/* Generated by bun run generate:styles. Edit tokens/index.ts or styles/components.css. */
:root {
${declarations(tokens)}
}
:root, [data-lotse-theme="light"] {
  color-scheme: light;
${declarations(colorTokens.light)}
${declarations(materialTokens.light)}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-lotse-theme="light"]) {
    color-scheme: dark;
${declarations(colorTokens.dark)}
${declarations(materialTokens.dark)}
  }
}
[data-lotse-theme="dark"] {
  color-scheme: dark;
${declarations(colorTokens.dark)}
${declarations(materialTokens.dark)}
}
${source}`;
const formatted = execFileSync("biome", ["format", "--stdin-file-path=src/styles.css"], {
  input: css,
  encoding: "utf8",
});
const output = new URL("../src/styles.css", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== formatted) throw new Error("UI_STYLES_OUT_OF_DATE");
} else {
  await writeFile(output, formatted);
}
